/**
 * Standard ERC-721 Transfer event — used to reconstruct current ownership
 * via `eth_getLogs` for collections that don't implement the optional
 * ERC-721 Enumerable extension (no `tokenOfOwnerByIndex`). Every conforming
 * ERC-721 contract MUST emit this on every mint/transfer/burn, so this is a
 * standards-compliant fallback rather than a third-party dependency.
 */
export const erc721TransferEvent = {
  type: "event",
  name: "Transfer",
  inputs: [
    { name: "from", type: "address", indexed: true },
    { name: "to", type: "address", indexed: true },
    { name: "tokenId", type: "uint256", indexed: true },
  ],
} as const;
